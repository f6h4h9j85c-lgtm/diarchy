// Budget line (1.4) and human slot (2.1)
// ---------------------------------------------------------------------------

export function budgetLine(state: GoalState | null): string {
  if (state === null) return "budget unavailable";
  const { used, limits } = state;
  let line =
    `${used.messages_total} of ${limits.messages_total} messages` +
    ` (PLAN ${used.plan_messages} of ${limits.plan_messages})` +
    `${SEP}${Math.floor(used.wall_clock_minutes)} of ${limits.wall_clock_minutes} min`;
  if (limits.spend_usd !== null) line += `${SEP}${used.spend_usd.toFixed(2)} of ${limits.spend_usd.toFixed(2)} USD`;
  const watch = state.deadlock_watch;
  if (watch !== null) line += `${SEP}open ${watch.decision_id}, DECIDE due by ${hms(watch.deadline)} UTC`;
  return line;
}

export function byId(messages: Message[]): Map<string, Message> {
  return new Map(messages.map((message) => [message.id, message]));
}

/** Messages in `(ts, seq)` order; ids sort the same way because ts is strictly increasing. */
export function sortMessages(messages: Message[]): Message[] {
  return [...messages].sort((a, b) => (a.ts < b.ts ? -1 : a.ts > b.ts ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

export function lastOfType(messages: Message[], type: MessageType): Message | undefined {
  for (let index = messages.length - 1; index >= 0; index -= 1) {
    if (messages[index].type === type) return messages[index];
  }
  return undefined;
}

/** The message that put the run into BLOCKED: the latest ASK_HUMAN, or a later human BLOCKED (`diarchy stop`, which pages nobody). */
export function blockTrigger(messages: Message[]): Message | undefined {
  const ask = lastOfType(messages, "ASK_HUMAN");
  const stop = [...messages].reverse().find((message) => message.type === "BLOCKED" && message.from === AGENT_HUMAN);
  if (ask === undefined) return stop;
  if (stop === undefined) return ask;
  return stop.ts > ask.ts ? stop : ask;
}

/** The ts the "human needed since" slot shows: the block's trigger, else the last message. */
export function humanNeededSince(messages: Message[]): string | undefined {
  return (blockTrigger(messages) ?? messages[messages.length - 1])?.ts;
}

export function humanSlot(state: GoalState | null, messages: Message[]): string {
  if (state?.phase !== "BLOCKED") return "no action needed";
  const since = humanNeededSince(messages);
  return since === undefined ? "**human needed**" : `**human needed** since ${hms(since)} UTC`;
}

/** The challengers, comma-separated (one in a two-agent run). */
export function challengerList(state: GoalState): string {
  return state.agents.filter((agent) => agent !== state.lead).join(", ");
}

export function decisionCount(messages: Message[]): number {
  return messages.filter((message) => message.type === "DECIDE").length;
}

export function navLine(messages: Message[]): string {
  return `[goal](goal.md)${SEP}[decisions (${decisionCount(messages)})](decisions.md)`;
}

/** Budget-triggered ASK_HUMAN (no reply_to): which counter tripped, read from the engine's body. */
export interface BudgetTrigger {
  counter: "messages_total" | "wall_clock_minutes" | "spend_usd";
  used: string;
  limit: string;
}

export function budgetTrigger(ask: Message, state: GoalState | null): BudgetTrigger {
  const total = /^Goal used (\d+) of (\d+) messages/.exec(ask.body);
  if (total) return { counter: "messages_total", used: total[1], limit: total[2] };
  const spend = /^Spend (\S+) of (\S+) USD/.exec(ask.body);
  if (spend) return { counter: "spend_usd", used: spend[1], limit: spend[2] };
  const clock = /^Wall clock (\d+) min/.exec(ask.body);
  const limit = clock ? clock[1] : String(state?.limits.wall_clock_minutes ?? "");
  return { counter: "wall_clock_minutes", used: String(Math.floor(state?.used.wall_clock_minutes ?? 0)), limit };
}
